"""
app/scoring/weights.py — веса групп факторов и потолки уверенности.

Почему именно так (выстрадано бектестом, см. AI_AGENTS/BRAIN.md v4-0):

1. Факторы внутри группы НЕ независимы. Тренд на трёх таймфреймах и RSI на трёх
   таймфреймах — это два наблюдения, а не шесть. Поэтому сначала факторы
   сворачиваются в оценку группы, и только потом группы голосуют.
2. Потолок уверенности по числу СОГЛАСНЫХ групп. Без него «уверенность»
   надувалась до 83% на боковике, где 20 факторов повторяли одну и ту же мысль.
3. «Уверенность» — это сила согласия аргументов, а не вероятность прибыли:
   на 10 345 реальных сделках корзина с уверенностью ≥75% показала PF 0.85
   против 1.03 у корзины <60%. Поэтому уверенность capped, а в интерфейсе
   всегда объясняется, что именно она означает.
"""

from __future__ import annotations

from typing import Dict

from app.analysis.base import Group

# Вес группы в итоговом направленном счёте.
GROUP_WEIGHTS: Dict[str, float] = {
    Group.TREND: 1.15,        # старшие ТФ задают контекст
    Group.STRUCTURE: 1.10,    # BOS/CHOCH — самый ранний признак смены тренда
    Group.MOMENTUM: 1.00,
    Group.SMC: 0.95,          # зоны входа, но сами по себе не направление
    Group.VOLUME: 0.85,
    Group.LEVELS: 0.80,
    Group.CONTEXT: 0.75,      # BTC/ширина рынка — фон, не триггер
    Group.DERIVATIVES: 0.70,  # funding/OI — информация о толпе
    Group.SENTIMENT: 0.40,    # новости/соцсети — шумный источник
}

# Ненаправленные группы.
POTENTIAL_WEIGHT = 1.0
QUALITY_WEIGHT = 1.0

# Потолок уверенности (0..10) по числу согласных независимых групп.
GROUP_CONFIDENCE_CAPS: Dict[int, float] = {
    0: 2.0,
    1: 4.0,
    2: 5.8,
    3: 7.2,
    4: 8.4,
    5: 9.2,
    6: 9.6,
}

# Порог, с которого фактор группы считается «согласным» с направлением.
AGREEMENT_THRESHOLD = 0.22

# Порог, с которого ГРУППА считается имеющей мнение (участвует в знаменателе).
OPINION_THRESHOLD = 0.10

# Масштаб счёта: score 0.55 и выше = 10 баллов уверенности (до применения
# потолков). Подбирался по распределению счёта: «хороший» setup с пятью
# согласными группами даёт score ~0.40–0.45, то есть ~7.5–8 баллов.
CONFIDENCE_FULL_SCORE = 0.55

# Диапазон влияния потенциала на уверенность: 0.85..1.10.
POTENTIAL_INFLUENCE = (0.85, 1.10)

# Влияние качества данных: 0.55..1.0 (плохие данные режут уверенность вдвое).
QUALITY_FLOOR = 0.55

# Минимальное число согласных групп, чтобы сигнал вообще мог быть actionable.
MIN_AGREEMENT = 2


def confidence_cap(agreement: int) -> float:
    if agreement >= max(GROUP_CONFIDENCE_CAPS):
        return GROUP_CONFIDENCE_CAPS[max(GROUP_CONFIDENCE_CAPS)]
    return GROUP_CONFIDENCE_CAPS.get(agreement, 9.6)
